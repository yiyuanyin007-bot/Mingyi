# 解析函数
def extract_rx_items(text, sorted_herbs):
    items = []
    if not text:
        return items
    
    # 方法：在文本中搜索每个已知药名，然后找后面的数字+单位
    for herb in sorted_herbs:
        # 药名前后不能是中文汉字（避免匹配到别的词内部）
        # 但允许前面是"、" "，" " " "：" "（"
        pattern = re.compile(r'(?<![一-龥])' + re.escape(herb) + r'(?![一-龥])')
        for m in pattern.finditer(text):
            # 从药名位置往后找 0-25 个字符内的 数字+单位
            after = text[m.end():m.end()+25]
            dm = re.search(r'\s*(\d+(?:\.\d+)?)\s*(克|g|G|公克|錢|钱|分)', after)
            if dm:
                dose = dm.group(1) + dm.group(2)
                # 去重
                if not any(i['name'] == herb for i in items):
                    items.append({'name': herb, 'dose': dose})
    return items

# 处理核心10方
target_formulas = ['大柴胡汤', '小柴胡汤', '四逆汤', '五苓散', '桂枝汤', '栀子厚朴汤', '小青龙汤', '麻黄汤', '真武汤', '柴胡加龙骨牡蛎汤']

for c in cards:
    if c['formula_name'] not in target_formulas:
        continue
    refs = c.get('references', {})
    for case in refs.get('clinical_cases', []):
        path = case.get('local_path', '')
        raw_text = ''
        if path and os.path.exists(path):
            with open(path, 'r', encoding='utf-8') as f:
                raw_text = f.read()
            if raw_text.startswith('---'):
                idx = raw_text.find('---', 3)
                if idx > 0:
                    raw_text = raw_text[idx + 3:].strip()
            raw_text = re.sub(r'^\s*\{[\s\S]*?\}\s*', '', raw_text).strip()
        
        summary = case.get('summary', '')
        search_text = raw_text if len(raw_text) > len(summary) else summary
        
        items = extract_rx_items(search_text, sorted_herbs)
        
        if items:
            case['prescription_structured'] = items
            case['prescription'] = '，'.join([f"{i['name']}{i['dose']}" for i in items])
            names = [i['name'] for i in items[:5]]
            print(f"OK: {c['formula_name'][:6]} - {case['title'][:20]} : {len(items)} herbs - {names}")
        else:
            # fallback: 匹配"XX数字克"
            all_matches = re.findall(r'([^，。、\s]{2,6})(\d+(?:\.\d+)?)\s*[克gG]', search_text)
            if all_matches:
                fallback_items = []
                for name, dose in all_matches:
                    if len(name) >= 2 and not name.isdigit():
                        fallback_items.append({'name': name, 'dose': dose + '克'})
                if fallback_items:
                    case['prescription_structured'] = fallback_items
                    case['prescription'] = '，'.join([f"{i['name']}{i['dose']}" for i in fallback_items])
                    names = [i['name'] for i in fallback_items[:5]]
                    print(f"FALLBACK: {c['formula_name'][:6]} - {case['title'][:20]} : {len(fallback_items)} herbs - {names}")
                else:
                    print(f"FAIL: {c['formula_name'][:6]} - {case['title'][:20]}")
            else:
                print(f"FAIL: {c['formula_name'][:6]} - {case['title'][:20]}")

with open('data/formula_cards.json', 'w', encoding='utf-8') as f:
    json.dump(cards, f, ensure_ascii=False, indent=2)

